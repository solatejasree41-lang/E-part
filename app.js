function selectedValues(name) {
    return [...document.querySelectorAll(`input[name="${name}"]:checked`)].map((input) => input.value);
}

function updateProducts() {
    const query = searchInput.value.trim().toLowerCase();
    const category = categorySelect.value;
    const devices = selectedValues("device");
    const brands = selectedValues("brand");
    const availability = selectedValues("availability");
    const services = selectedValues("service");
    const priceRange = document.querySelector('input[name="price"]:checked')?.value;

    const matchingProducts = products.filter((product) => {
        const searchableText = `${product.textContent} ${product.dataset.models || ""}`.toLowerCase();
        const price = Number(product.dataset.price);
        const matchesPrice = !priceRange
            || (priceRange === "under500" && price < 500)
            || (priceRange === "500to1500" && price >= 500 && price <= 1500)
            || (priceRange === "1500to5000" && price > 1500 && price <= 5000);

        return (!query || searchableText.includes(query))
            && (category === "all" || product.dataset.category === category)
            && (!devices.length || devices.includes(product.dataset.category))
            && (!brands.length || brands.includes(product.dataset.brand))
            && availability.every((value) => product.dataset.availability.split(" ").includes(value))
            && (!services.length || services.includes(product.dataset.service))
            && matchesPrice;
    });

    const sortMode = sortSelect.value;
    matchingProducts.sort((first, second) => {
        if (sortMode === "low") return Number(first.dataset.price) - Number(second.dataset.price);
        if (sortMode === "high") return Number(second.dataset.price) - Number(first.dataset.price);
        if (sortMode === "rating") return Number(second.dataset.rating) - Number(first.dataset.rating);
        return Number(first.dataset.order) - Number(second.dataset.order);
    });

    matchingProducts.forEach((product) => productGrid.append(product));
    products.forEach((product) => {
        product.hidden = !matchingProducts.includes(product);
    });

    resultCount.textContent = `Showing ${matchingProducts.length} of ${products.length} parts`;
    emptyState.hidden = matchingProducts.length > 0;
}

function showToast(message) {
    toast.textContent = message;
    toast.classList.add("is-visible");
    window.clearTimeout(toastTimer);
    toastTimer = window.setTimeout(() => toast.classList.remove("is-visible"), 2800);
}

function renderFollowUpQuestions() {
    const questions = followUpConfig[damageProblem.value] || [];
    followUpQuestions.replaceChildren();
    followUpQuestions.hidden = questions.length === 0;

    if (!questions.length) return;

    const heading = document.createElement("h3");
    heading.textContent = "A few follow-up questions";
    followUpQuestions.append(heading);

    questions.forEach((question) => {
        const label = document.createElement("label");
        label.className = "follow-up-field";
        label.htmlFor = `followUp-${question.id}`;
        label.append(document.createTextNode(question.question));

        let input;
        if (question.type === "textarea") {
            input = document.createElement("textarea");
            input.rows = 3;
            input.placeholder = "Describe the problem";
        } else {
            input = document.createElement("select");
            const placeholder = document.createElement("option");
            placeholder.value = "";
            placeholder.textContent = "Choose an answer";
            input.append(placeholder);
            question.options.forEach((answer) => {
                const option = document.createElement("option");
                option.value = answer;
                option.textContent = answer;
                input.append(option);
            });
        }

        input.id = `followUp-${question.id}`;
        input.name = question.id;
        input.required = true;
        label.append(input);
        followUpQuestions.append(label);
    });
}

function getFollowUpAnswers() {
    const answers = {};
    (followUpConfig[damageProblem.value] || []).forEach((question) => {
        answers[question.id] = document.querySelector(`[name="${question.id}"]`).value.trim();
    });
    return answers;
}

function getDiagnosis(answers) {
    const causes = [];
    let partIds = [];

    if (damageProblem.value === "no-power") {
        if (answers.outletTest === "Not yet") {
            causes.push("A wall outlet, power cable, or connection issue should be ruled out first.");
        }
        if (answers.standbyLight === "No") {
            causes.push("The power supply board may not be providing standby power.");
            partIds.push("power");
        } else if (answers.standbyLight === "Yes") {
            causes.push("The main board or startup controls may be preventing the TV from turning on.");
            partIds.push("main");
        } else {
            causes.push("The power supply board or main board may be involved.");
            partIds.push("power", "main");
        }
    } else if (damageProblem.value === "blank-screen") {
        if (answers.soundWithBlank === "Yes") {
            causes.push("The display panel or its backlight may be involved when sound is present but no picture appears.");
            partIds.push("display");
        } else {
            causes.push("The main board, display panel, or a video-input issue may be involved.");
            partIds.push("main", "display");
        }
        if (answers.faintPicture === "Yes") {
            causes.push("A faint image can be consistent with a backlight issue; this needs technician inspection.");
        }
    } else if (damageProblem.value === "no-sound") {
        if (answers.muted === "Yes") {
            causes.push("A mute or volume setting may explain the symptom; check settings before replacing parts.");
        } else if (answers.externalAudio === "Yes") {
            causes.push("The TV speaker connection or internal audio path may be involved.");
            partIds.push("main");
        } else {
            causes.push("The main board or audio output path may be involved.");
            partIds.push("main");
        }
    } else if (damageProblem.value === "display") {
        if (answers.displaySymptom === "Crack or dark patches" || answers.displayArea === "Only a small area") {
            causes.push("The display panel may be damaged, especially if a crack or localized dark area is visible.");
            partIds.push("display");
        } else if (answers.displaySymptom === "Lines or flickering") {
            causes.push("The display panel, internal display connections, or main board may be involved.");
            partIds.push("display", "main");
        } else {
            causes.push("The display panel or main board may be involved.");
            partIds.push("display", "main");
        }
    } else if (damageProblem.value === "restarting") {
        if (answers.restartAccessories === "No") {
            causes.push("An external device or connection may be triggering the restarts.");
        } else if (answers.restartTiming === "While starting up") {
            causes.push("The power supply board or main board may be having trouble during startup.");
            partIds.push("power", "main");
        } else {
            causes.push("The power supply board or main board may be causing repeated restarts.");
            partIds.push("power", "main");
        }
    } else {
        causes.push("The symptom needs more information and an in-person assessment before a part can be suggested.");
        if (answers.otherDetails) {
            causes.push(`Your description: ${answers.otherDetails}`);
        }
    }

    return {
        causes: [...new Set(causes)],
        parts: [...new Set(partIds)].map((partId) => partCatalog[partId])
    };
}

function appendLabeledText(parent, labelText, value) {
    const line = document.createElement("p");
    const label = document.createElement("strong");
    label.textContent = `${labelText}: `;
    line.append(label, document.createTextNode(value));
    parent.append(line);
}

