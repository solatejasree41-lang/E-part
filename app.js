function openTechnicianForm() {
    technicianForm.hidden = false;
    bookingConfirmation.hidden = true;
    const issue = problemLabels[damageProblem.value];
    const model = damageModel.value.trim();
    const deviceType = document.querySelector("#technicianDeviceType");
    if (damageProblem.value) {
        deviceType.value = "TV";
        document.querySelector("#technicianBrandModel").value =
            `Samsung ${model || "(model unknown)"}`;
        document.querySelector("#technicianNotes").value = [
            issue ? `Reported problem: ${issue}` : "",
            model ? `Model: ${model}` : "",
            ...Object.entries(getFollowUpAnswers()).map(([questionId, answer]) => {
                    const question = (followUpConfig[damageProblem.value] || [])
                        .find((item) => item.id === questionId);
                    return `${question ? question.question : questionId}: ${answer}`;
                }).filter((answer) => !answer.endsWith(": "))
        ].filter(Boolean).join("\n");
    }
    technicianForm.scrollIntoView({ behavior: "smooth", block: "center" });
    document.querySelector("#technicianName").focus({ preventScroll: true });
}

function openBookingFromProduct(product) {
    const deviceTypeByCategory = {
        tv: "TV",
        mobile: "Mobile phone",
        laptop: "Laptop",
        refrigerator: "Refrigerator"
    };
    const brand = product.dataset.brand
        ? `${product.dataset.brand[0].toUpperCase()}${product.dataset.brand.slice(1)}`
        : "";
    const model = product.dataset.models
        ? product.dataset.models.split(" ")[0]
        : "model unknown";

    openTechnicianForm();
    document.querySelector("#technicianDeviceType").value =
        deviceTypeByCategory[product.dataset.category] || "Other electronic device";
    document.querySelector("#technicianBrandModel").value =
        `${brand} ${model}`.trim() || "Unknown / not sure";
    document.querySelector("#technicianNotes").value =
        `Please inspect my ${product.dataset.category} device. I have not purchased a spare part and am requesting an independent technician visit.`;
}

